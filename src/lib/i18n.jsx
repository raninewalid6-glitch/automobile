const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("site_lang") || "fr");

  // Mémorise la langue et bascule le sens de lecture (droite-à-gauche pour l'arabe)
  useEffect(() => {
    localStorage.setItem("site_lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  // t("clé") -> texte dans la langue choisie (retombe sur le français si absent)
  const t = (key) => translations[lang]?.[key] ?? translations.fr[key] ?? key;

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLang = () => useContext(LanguageContext);
